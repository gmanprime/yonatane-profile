'use client';

import React from 'react';
import type { ResolvedProfileItem } from '@/lib/types/profile.types';
import { formatHref } from '@/lib/utils/url';
import styles from '../client.module.css';

interface ProfileItemData {
  network?: string;
  username?: string;
  website?: string | { url?: string; label?: string };
  url?: string;
  icon?: string;
}

interface ProfilesSectionProps {
  items: ResolvedProfileItem[];
}

const getNetworkIcon = (network: string) => {
  const n = network.toLowerCase();
  if (n.includes('github')) {
    return (
      <svg width="20" height="20" viewBox="0 0 24 24" fill="currentColor">
        <path d="M12 0C5.37 0 0 5.37 0 12c0 5.31 3.435 9.795 8.205 11.385.6.105.825-.255.825-.57 0-.285-.015-1.23-.015-2.235-3.015.555-3.795-.735-4.035-1.41-.135-.345-.72-1.41-1.23-1.695-.42-.225-1.02-.78-.015-.795.945-.015 1.62.87 1.845 1.23 1.08 1.815 2.805 1.305 3.495.99.105-.78.42-1.305.765-1.605-2.67-.3-5.46-1.335-5.46-5.925 0-1.305.465-2.385 1.23-3.225-.12-.3-.54-1.53.12-3.18 0 0 1.005-.315 3.3 1.23.96-.27 1.98-.405 3-.405s2.04.135 3 .405c2.295-1.56 3.3-1.23 3.3-1.23.66 1.65.24 2.88.12 3.18.765.84 1.23 1.905 1.23 3.225 0 4.605-2.805 5.625-5.475 5.925.435.375.81 1.095.81 2.22 0 1.605-.015 2.895-.015 3.3 0 .315.225.69.825.57A12.02 12.02 0 0024 12c0-6.63-5.37-12-12-12z" />
      </svg>
    );
  }
  if (n.includes('linkedin')) {
    return (
      <svg width="20" height="20" viewBox="0 0 24 24" fill="currentColor">
        <path d="M19 0h-14c-2.761 0-5 2.239-5 5v14c0 2.761 2.239 5 5 5h14c2.762 0 5-2.239 5-5v-14c0-2.761-2.238-5-5-5zm-11 19h-3v-11h3v11zm-1.5-12.268c-.966 0-1.75-.79-1.75-1.764s.784-1.764 1.75-1.764 1.75.79 1.75 1.764-.783 1.764-1.75 1.764zm13.5 12.268h-3v-5.604c0-3.368-4-3.113-4 0v5.604h-3v-11h3v1.765c1.396-2.586 7-2.777 7 2.476v6.759z" />
      </svg>
    );
  }
  if (n.includes('twitter') || n.includes('x.com') || n === 'x') {
    return (
      <svg width="20" height="20" viewBox="0 0 24 24" fill="currentColor">
        <path d="M18.244 2.25h3.308l-7.227 8.26 8.502 11.24H16.17l-5.214-6.817L4.99 21.75H1.68l7.73-8.835L1.254 2.25H8.08l4.713 6.231zm-1.161 17.52h1.833L7.084 4.126H5.117z" />
      </svg>
    );
  }
  return (
    <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
      <circle cx="12" cy="12" r="10" />
      <line x1="2" y1="12" x2="22" y2="12" />
      <path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z" />
    </svg>
  );
};

export const ProfilesSection: React.FC<ProfilesSectionProps> = ({ items }) => {
  if (items.length === 0) return null;

  return (
    <div className={styles.profilesGrid}>
      {items.map((item) => {
        const data = item.data as ProfileItemData;
        const network = data.network || 'Profile';
        const username = data.username || '';
        const rawUrl = typeof data.website === 'object' ? data.website?.url : (data.website || data.url);
        const urlHref = formatHref(rawUrl);

        const cardContent = (
          <>
            <div className={styles.socialIconWrapper}>{getNetworkIcon(network)}</div>
            <div style={{ minWidth: 0, flex: 1 }}>
              <div className={styles.socialNetwork}>{network}</div>
              {username && <div className={styles.socialUsername}>@{username}</div>}
            </div>
            <svg
              width="14"
              height="14"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="2.5"
              style={{ color: 'var(--theme-accent, #38bdf8)', flexShrink: 0 }}
            >
              <path d="M18 13v6a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h6" />
              <polyline points="15 3 21 3 21 9" />
              <line x1="10" y1="14" x2="21" y2="3" />
            </svg>
          </>
        );

        if (urlHref) {
          return (
            <a
              key={item.id}
              href={urlHref}
              target="_blank"
              rel="noopener noreferrer"
              className={styles.profileSocialCard}
              title={`Visit ${username || network}`}
            >
              {cardContent}
            </a>
          );
        }

        return (
          <div key={item.id} className={styles.profileSocialCard}>
            {cardContent}
          </div>
        );
      })}
    </div>
  );
};
